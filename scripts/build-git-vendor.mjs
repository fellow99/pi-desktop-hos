#!/usr/bin/env node
/**
 * build-git-vendor.mjs — 构建 harmony-git 扩展的**第三方运行时单文件 bundle**。
 *
 * 为什么需要它（需求 204-plugin-git）：
 *   设备上没有 git 二进制，`PI_OFFLINE=1` 也禁止运行期联网安装 npm 包，因此纯 JS 的
 *   isomorphic-git 必须**随扩展一起物化**到设备。pi 的扩展经 jiti 从扩展自己所在目录解析
 *   兄弟模块，pi-web 的 node_modules 不在解析路径上，所以把 isomorphic-git 与其 Node HTTP
 *   客户端、以及 diff 渲染所需的 jsdiff 一起 esbuild 预打成**一个 CJS 文件**，放进扩展的
 *   `vendor/` 目录，随 `extensions/` 树递归 copy 到 `<pi-agent>/extensions/harmony-git/vendor/`。
 *
 * 产物：`extensions/harmony-git/vendor/isomorphic-git.bundle.cjs`
 *   - `--platform=node` 且所有 `node:*` 内置模块 external（设备 Node 运行时自带，不打进包）；
 *   - CJS：经 jiti 以 `jiti.import(path, { default: true })` 加载，`default` 即 isomorphic-git
 *     命名空间，并在其上挂 `http` / `createTwoFilesPatch` / `structuredPatch`；
 *   - 纯 JS、无 `.node` 原生插件（isomorphic-git 全闭包无原生依赖）。
 *
 * 可复现：版本在下方常量 pin 死；需要联网（仅构建机，一次性）。设备端永不执行本脚本。
 *
 * 用法：
 *   node scripts/build-git-vendor.mjs            # 构建并写产物（需要本机已 npm install 或可联网）
 *   node scripts/build-git-vendor.mjs --verify   # 只校验已提交产物的版本与入口，不联网
 */

import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(HERE, '..');
const EXT_DIR = path.join(PROJECT_ROOT, 'extensions', 'harmony-git');
const VENDOR_DIR = path.join(EXT_DIR, 'vendor');
const OUT_FILE = path.join(VENDOR_DIR, 'isomorphic-git.bundle.cjs');

/** 版本 pin：升级时改这里并同步 docs/204-插件-GIT.md。 */
const ISOMORPHIC_GIT_VERSION = '1.44.2';
const DIFF_VERSION = '9.0.0';
const ESBUILD_VERSION = '0.28.2';

const require = createRequire(import.meta.url);

function log(...parts) {
  console.log('[build-git-vendor]', ...parts);
}

/** 在一个临时目录里准备 esbuild + 两个运行时依赖（构建机可联网）。 */
async function ensureStage() {
  const stage = await fsp.mkdtemp(path.join(process.env.TEMP || process.env.TMPDIR || '.', 'git-vendor-'));
  await fsp.writeFile(
    path.join(stage, 'package.json'),
    JSON.stringify({ name: 'git-vendor-stage', private: true }, null, 2),
  );
  const isWin = process.platform === 'win32';
  const npm = isWin ? 'npm' : 'npm';
  log(`npm install (stage=${stage}) …`);
  execFileSync(
    npm,
    ['install', '--no-audit', '--no-fund',
      `isomorphic-git@${ISOMORPHIC_GIT_VERSION}`,
      `diff@${DIFF_VERSION}`,
      `esbuild@${ESBUILD_VERSION}`],
    { cwd: stage, stdio: 'inherit', shell: isWin },
  );
  return stage;
}

function banner() {
  return '/* harmony-git vendor bundle | '
    + `isomorphic-git@${ISOMORPHIC_GIT_VERSION} + isomorphic-git/http/node + diff@${DIFF_VERSION} | `
    + `built with esbuild@${ESBUILD_VERSION} (node: builtins external, platform=node, format=cjs) | `
    + 'generated by scripts/build-git-vendor.mjs — DO NOT EDIT BY HAND */';
}

const VENDOR_ENTRY = `// Auto-generated entry for the harmony-git vendor bundle.
const git = require('isomorphic-git');
const http = require('isomorphic-git/http/node');
const { createTwoFilesPatch, structuredPatch } = require('diff');
module.exports = git;
module.exports.http = http;
module.exports.createTwoFilesPatch = createTwoFilesPatch;
module.exports.structuredPatch = structuredPatch;
`;

/** node 内置模块全部 external（含 isomorphic-git/http/node 经 simple-get 用到的）。 */
const NODE_EXTERNALS = [
  'crypto', 'fs', 'path', 'http', 'https', 'zlib', 'stream', 'url', 'os', 'util',
  'events', 'buffer', 'string_decoder', 'process', 'net', 'tls', 'async_hooks',
];

async function build() {
  const stage = await ensureStage();
  try {
    const entry = path.join(stage, 'vendor-entry.cjs');
    await fsp.writeFile(entry, VENDOR_ENTRY);
    const esbuildBin = path.join(stage, 'node_modules', 'esbuild', 'bin', 'esbuild');
    await fsp.mkdir(VENDOR_DIR, { recursive: true });
    const args = [
      entry,
      '--bundle', '--format=cjs', '--platform=node',
      ...NODE_EXTERNALS.map((m) => `--external:${m}`),
      `--banner:js=${banner()}`,
      '--legal-comments=none',
      `--outfile=${OUT_FILE}`,
    ];
    log('esbuild …');
    execFileSync(process.execPath, [esbuildBin, ...args], { stdio: 'inherit' });
    const stat = await fsp.stat(OUT_FILE);
    const buf = await fsp.readFile(OUT_FILE);
    log(`wrote ${path.relative(PROJECT_ROOT, OUT_FILE)} (${stat.size} bytes, sha256 ${sha256(buf).slice(0, 16)}…)`);
    await verify(buf);
  } finally {
    await fsp.rm(stage, { recursive: true, force: true }).catch(() => {});
  }
}

function sha256(buf) {
  return createHash('sha256').update(buf).digest('hex');
}

/**
 * 校验已提交产物：可被 require、版本匹配、关键入口存在。`--verify` 走这条且不联网。
 * 用隔离的 require 从绝对路径加载 CJS bundle。
 */
async function verify(preloaded) {
  if (!fs.existsSync(OUT_FILE)) throw new Error(`vendor bundle missing: ${OUT_FILE}`);
  const buf = preloaded ?? await fsp.readFile(OUT_FILE);
  const mod = require(OUT_FILE);
  const actual = typeof mod.version === 'function' ? mod.version() : 'unknown';
  const checks = {
    version: actual === ISOMORPHIC_GIT_VERSION,
    init: typeof mod.init === 'function',
    clone: typeof mod.clone === 'function',
    statusMatrix: typeof mod.statusMatrix === 'function',
    httpRequest: typeof mod.http?.request === 'function',
    createTwoFilesPatch: typeof mod.createTwoFilesPatch === 'function',
  };
  const failed = Object.entries(checks).filter(([, ok]) => !ok).map(([k]) => k);
  if (actual !== ISOMORPHIC_GIT_VERSION) {
    throw new Error(`vendor bundle version ${actual} != pinned ${ISOMORPHIC_GIT_VERSION}`);
  }
  if (failed.length > 0) throw new Error(`vendor bundle entry check failed: ${failed.join(', ')}`);
  log(`verify OK: isomorphic-git ${actual}, http/node, createTwoFilesPatch present; sha256 ${sha256(buf).slice(0, 16)}…`);
}

const mode = process.argv[2] === '--verify' ? 'verify' : 'build';
if (mode === 'verify') {
  await verify();
} else {
  await build();
}
